/**
 * 给外部导入的 skill 自动补齐输出契约。
 * 少了「只输出 JSON」这段，卡片就拿不到可解析的 JSON —— 这是导入功能最常踩的坑。
 */
fun ensureJsonContract(text: String): String =
    if (text.contains("replies") && text.contains("intent")) {
        text
    } else {
        text.trimEnd() + "\n\n" + JSON_CONTRACT
    }
